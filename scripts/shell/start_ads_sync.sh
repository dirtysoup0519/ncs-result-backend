#!/usr/bin/env bash
set -Eeuo pipefail

# Zero-config starter for the VM ADS sync watcher.
# Baseline assumption: the VM provides ONLY MySQL (root@127.0.0.1, skip-grant
# recovery mode). Everything else is bootstrapped automatically:
#   - picks the best available Python (3.12 > 3.11 > 3.10 > 3)
#   - ensures PyMySQL is importable (pip install, skippable via NCS_PIP_INSTALL=0)
#   - creates the exchange directory tree
#   - generates <repo>/../ncs-runtime/ads-sync.env on first run
#   - checks MySQL connectivity (warning only, never fatal)
#
# Usage:
#   start_ads_sync.sh                 foreground watch (default)
#   start_ads_sync.sh --once          run a single sync round and print its exit code
#   start_ads_sync.sh --detach        start watch in the background (nohup + pidfile)
#   start_ads_sync.sh --stop          stop a watcher started with --detach
#   start_ads_sync.sh --init          (re)apply the ADS schema before starting
#   start_ads_sync.sh --db-url URL    MySQL URL used when generating a fresh env file
#   start_ads_sync.sh --env FILE      env file to source/generate
#                                     (default: $NCS_ADS_SYNC_ENV, then
#                                      <repo>/../ncs-runtime/ads-sync.env)
#
# NCS_ADS_EXCHANGE_ROOT must be absolute; a relative value is rejected.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

ONCE=0
DETACH=0
STOP=0
INIT=0
DB_URL=""
ENV_FILE="${NCS_ADS_SYNC_ENV:-$REPO_DIR/../ncs-runtime/ads-sync.env}"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --env) ENV_FILE="$2"; shift 2 ;;
    --db-url) DB_URL="$2"; shift 2 ;;
    --once) ONCE=1; shift ;;
    --detach) DETACH=1; shift ;;
    --stop) STOP=1; shift ;;
    --init) INIT=1; shift ;;
    -h|--help) sed -n '2,26p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "start_ads_sync: unknown option: $1" >&2; exit 2 ;;
  esac
done

say() { printf 'start_ads_sync: %s\n' "$*"; }
die() { printf 'start_ads_sync: %s\n' "$*" >&2; exit 2; }

# $1 = an NCS_ADS_EXCHANGE_ROOT value. It must already be absolute: prefixing
# REPO_DIR onto a Windows path turns "C:\...\exchange" into
# "<repo>/C:\...\exchange", and MSYS rewrites the now-illegal colon to U+F03A,
# so the whole exchange tree silently appears inside the repo as
# "C" + U+F03A + "/Users/...". Leave a drive path untouched on MSYS instead,
# and refuse anything that is not absolute.
require_absolute_root() {
  case "$1" in
    /*) return 0 ;;
    [A-Za-z]:[\\/]*)
      case "$(uname -s)" in
        MINGW*|MSYS*|CYGWIN*) return 0 ;;
      esac
      die "NCS_ADS_EXCHANGE_ROOT must be an absolute POSIX path on this host (got: $1)"
      ;;
  esac
  die "NCS_ADS_EXCHANGE_ROOT must be an absolute path (got: $1)"
}

find_python() {
  local c
  for c in python3.12 python3.11 python3.10 python3; do
    command -v "$c" >/dev/null 2>&1 && { printf '%s' "$c"; return 0; }
  done
  return 1
}

# --- bootstrap: env file -----------------------------------------------------
if [[ "$STOP" -eq 0 && ! -f "$ENV_FILE" ]]; then
  # Validate before writing: a bad value baked into the generated file would
  # win over the environment on every later run (the file is sourced), so
  # fixing the variable alone would never recover.
  require_absolute_root "${NCS_ADS_EXCHANGE_ROOT:-$REPO_DIR/../ncs-ads-exchange}"
  mkdir -p "$(dirname "$ENV_FILE")"
  PY="$(find_python)" || die "no python3 interpreter found on this machine"
  say "first run: generating $ENV_FILE"
  {
    echo "# Generated by start_ads_sync.sh on $(date '+%F %T'); edit freely, values are kept."
    echo "export NCS_REPO='$REPO_DIR'"
    echo "export NCS_DATABASE_URL='${DB_URL:-mysql+pymysql://root@127.0.0.1:3306/ncs_analytics}'"
    echo "export NCS_ADS_EXCHANGE_ROOT='${NCS_ADS_EXCHANGE_ROOT:-$REPO_DIR/../ncs-ads-exchange}'"
    echo "export NCS_PYTHON_BIN='$(command -v "$PY")'"
    echo "export NCS_LOG_TZ='Asia/Shanghai'"
  } > "$ENV_FILE"
  chmod 600 "$ENV_FILE" 2>/dev/null || true
  say "edit $ENV_FILE to point NCS_DATABASE_URL at this machine's MySQL if needed"
fi

if [[ -f "$ENV_FILE" ]]; then
  # shellcheck disable=SC1090
  source "$ENV_FILE"
else
  die "env file not found: $ENV_FILE (remove --stop or create the file first)"
fi

: "${NCS_REPO:?NCS_REPO must be set (in $ENV_FILE)}"
: "${NCS_DATABASE_URL:?NCS_DATABASE_URL must be set (in $ENV_FILE)}"
if [[ -z "${NCS_PYTHON_BIN:-}" ]]; then
  PY="$(find_python)" || die "no python3 interpreter found on this machine"
  NCS_PYTHON_BIN="$(command -v "$PY")"
fi
export NCS_PYTHON_BIN

# --- bootstrap: exchange directories ----------------------------------------
ROOT="${NCS_ADS_EXCHANGE_ROOT:-$REPO_DIR/../ncs-ads-exchange}"
require_absolute_root "$ROOT"
export NCS_ADS_EXCHANGE_ROOT="$ROOT"
READY="$ROOT/ready"; ARCHIVE="$ROOT/archive"; REJECTED="$ROOT/rejected"
LOGS="$ROOT/logs"; LOCKS="$ROOT/locks"
PID_FILE="$LOCKS/watch_ads.pid"
if [[ "$STOP" -eq 0 ]]; then
  mkdir -p "$READY" "$ROOT/processing" "$ARCHIVE" "$REJECTED" "$LOGS" "$LOCKS"
fi

# --- bootstrap: dependencies (skippable, warning-only) -----------------------
if [[ "$STOP" -eq 0 ]]; then
  if ! "$NCS_PYTHON_BIN" -c 'import pymysql' 2>/dev/null; then
    if [[ "${NCS_PIP_INSTALL:-1}" == "1" ]]; then
      say "PyMySQL missing; installing via pip"
      "$NCS_PYTHON_BIN" -m pip install --quiet pymysql 2>/dev/null \
        || "$NCS_PYTHON_BIN" -m pip install --quiet --user pymysql 2>/dev/null \
        || say "WARNING: pip install failed (offline?); run it manually before the first real import"
    else
      say "WARNING: PyMySQL missing and NCS_PIP_INSTALL=0; import will fail until installed"
    fi
  fi
fi

# --- bootstrap: MySQL connectivity (warning-only) -----------------------------
if [[ "$STOP" -eq 0 && "$INIT" -eq 0 ]]; then
  "$NCS_PYTHON_BIN" - "$NCS_DATABASE_URL" <<'PYEOF' 2>/dev/null \
    || say "WARNING: MySQL not reachable yet; watcher will keep retrying on every round"
import sys
try:
    import pymysql
except ImportError:
    sys.exit(0)  # dependency warning handled above, stay quiet here
from urllib.parse import urlsplit
parts = urlsplit(sys.argv[1])
pymysql.connect(
    host=parts.hostname or "127.0.0.1",
    port=parts.port or 3306,
    user=parts.username or "root",
    passwd=parts.password or "",
    database=parts.path.lstrip("/") or None,
    connect_timeout=3,
)
print("start_ads_sync: MySQL connection OK")
PYEOF
fi

# --- optional schema initialization -------------------------------------------
if [[ "$INIT" -eq 1 ]]; then
  say "applying ADS schema via setup_mysql_ads.py"
  (cd "$REPO_DIR" && "$NCS_PYTHON_BIN" scripts/setup_mysql_ads.py --initialize --url "$NCS_DATABASE_URL")
fi

# --- dispatch ------------------------------------------------------------------
watch_running() {
  [[ -f "$PID_FILE" ]] || return 1
  local pid
  pid="$(cat "$PID_FILE" 2>/dev/null)" || return 1
  kill -0 "$pid" 2>/dev/null
}

if [[ "$STOP" -eq 1 ]]; then
  if ! watch_running; then
    say "watcher is not running (pid file: $PID_FILE)"
    rm -f -- "$PID_FILE"
    exit 1
  fi
  PID="$(cat "$PID_FILE")"
  kill "$PID"
  for _ in $(seq 1 20); do
    kill -0 "$PID" 2>/dev/null || break
    sleep 0.5
  done
  if kill -0 "$PID" 2>/dev/null; then
    kill -9 "$PID" 2>/dev/null || true
  fi
  rm -f -- "$PID_FILE"
  say "watcher $PID stopped"
  exit 0
fi

if [[ "$ONCE" -eq 1 ]]; then
  rc=0
  bash "$REPO_DIR/scripts/shell/sync_ads_once.sh" || rc=$?
  say "sync_ads_once exit=$rc"
  exit "$rc"
fi

if [[ "$DETACH" -eq 1 ]]; then
  if watch_running; then
    say "watcher already running (pid $(cat "$PID_FILE"))"
    exit 1
  fi
  WATCH_LOG="$LOGS/watch_ads.log"
  nohup bash "$REPO_DIR/scripts/shell/watch_ads.sh" >>"$WATCH_LOG" 2>&1 &
  echo $! > "$PID_FILE"
  say "watcher started in background (pid $!, log: $WATCH_LOG)"
  exit 0
fi

cd "$REPO_DIR"
exec bash "$REPO_DIR/scripts/shell/watch_ads.sh"
